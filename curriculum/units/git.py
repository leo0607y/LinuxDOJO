def G(*ops, identity=True):
    return {"identity": identity, "ops": list(ops)}


def goal(check):
    """現在のリポジトリを調べる判定。リポジトリの外などで例外になったら未達成。"""
    def run(t):
        try:
            key, repo = find_repo(t)
            return bool(check(t, repo))
        except Exception:
            return False
    return run


def messages(repo):
    return [repo["commits"][c]["msg"] for c in history(repo, head_id(repo))]


def repo_at(t, key):
    return state(t)["repos"].get(key)


