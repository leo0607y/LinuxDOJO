AUTHORING_NOTICE = (
    "\nここではスクリプトの保存内容を確認します。実行結果は判定しません。"
    "vim やテキスト加工で編集できます。入力例は本文の各行を引用して、1回の入力で保存する形です。"
    "実際の実行・動作確認は実践モード Stage 6 で行います。"
)


def source_goal(name, source):
    """Allow indentation/trailing-space differences while checking the authored source."""
    def lines(text):
        return [line.strip() for line in text.splitlines() if line.strip()]

    def check(terminal):
        path = terminal.path(name)
        return path.is_file() and lines(path.read_text(encoding="utf-8")) == lines(source)
    return check


def write_command(name, source):
    return "printf '%s\\n' " + " ".join(shlex.quote(line) for line in source.rstrip("\n").split("\n")) + " > " + name


def L(number, name, title, explanation, task, source, success, thinking, tool, **extra):
    command = write_command(name, source)
    return lesson(
        f"ex-scripting-{number:02d}", title, explanation + AUTHORING_NOTICE,
        task, command, success + " 保存内容を確認しました。実行確認は Stage 6 へ進みましょう。",
        cwd="scripting", files={name: "#!/bin/bash\n# TODO: 要件を満たす処理をここに書く\n"},
        goal=source_goal(name, source),
        hints=[thinking, tool, "入力例: " + command],
        source_file=name, source=source, **extra,
    )


