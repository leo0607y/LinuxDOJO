_COMMON_WORDS = {"pwd", "ls", "cd", "cat", "echo", "hint", "lesson", "reset", "menu", "esc", "exit", "whoami", "hostname"}


def _is_sentence(line):
    """vim の入力モードで書いた「文」と見なせる行（コマンド名だけの入力は除く）。"""
    text = line.strip()
    return len(text) >= 4 and text.split()[0] not in _COMMON_WORDS


