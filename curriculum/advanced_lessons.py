def _env_is(name, value):
    return lambda t: t.progress["env"].get(name) == value


def _no_process(pid):
    return lambda t: all(p["pid"] != pid for p in t.progress["processes"])


def _conf_line(text):
    return editor(lambda e: text in e["lines"])


