def _row(p):
    """ps aux の1行と同じ書式（grep で抜き出した結果の期待値に使う）。"""
    return f"{p['user']:<10} {p['pid']:>5} {p['cpu']:>4.1f} {p['mem']:>4.1f} {p['cmd']}"


def _rows(*items):
    return "".join(_row(p) + "\n" for p in items)


